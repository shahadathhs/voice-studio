/// Words ending in -er whose r is said.
const ER_SAID: &[&str] = &[
    "hiver", "enfer", "super", "amer", "cancer", "laser", "fier", "hier",
];

pub fn spelled(word: &str) -> Option<&'static str> {
    WORDS.iter().find(|(w, _)| *w == word).map(|(_, p)| *p)
}

pub fn noun_ent(word: &str) -> bool {
    NOUN_ENT.contains(&word)
}

pub fn er_said(word: &str) -> bool {
    ER_SAID.contains(&word)
}
