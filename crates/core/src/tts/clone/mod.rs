//! Voice cloning with Chatterbox Multilingual (MIT), run with ONNX Runtime on this computer.
//!
//! A short recording of one speaker becomes a [`ClonedVoice`]; [`CloneEngine::speak`] then says any
//! text in that voice. English, Spanish, French, Italian, Portuguese and Hindi are supported; see
//! [`language`] for what is not.
//!
//! **Safety is part of the feature.** A voice cannot be made without a [`Consent`]; every voice is
//! marked `cloned`; audio made with one should carry the [`DISCLOSURE`] note (WAV and FLAC files
//! can hold it); a voice can be deleted; no voice of anyone else is ever shipped. The reference
//! implementation also adds a Perth watermark. That is a Python library and is **not** ported, so
//! this audio is not watermarked.

