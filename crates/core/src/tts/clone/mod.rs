/// The catalog id of the Chatterbox model.
pub const MODEL_ID: &str = "chatterbox-multilingual";
/// File names inside the model's folder; `catalog/models.json` lists the same names.
pub const ENCODER_FILE: &str = "speech_encoder.onnx";
pub const EMBED_FILE: &str = "embed_tokens.onnx";
pub const LANGUAGE_MODEL_FILE: &str = "language_model_q4.onnx";
pub const DECODER_FILE: &str = "conditional_decoder.onnx";
pub const TOKENIZER_FILE: &str = "tokenizer.json";
/// Chatterbox speaks at this rate.
pub const SAMPLE_RATE: u32 = 24_000;
/// Stored in WAV and FLAC files made with a cloned voice.
pub const DISCLOSURE: &str = "Synthetic voice generated by Voice Studio";

fn now_seconds() -> u64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map_or(0, |elapsed| elapsed.as_secs())
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::Error;

    #[test]
    fn a_missing_model_is_reported_as_not_installed() {
        let dir = tempfile::tempdir().unwrap();
        let result = CloneEngine::load(dir.path());
        assert!(matches!(result, Err(Error::ModelMissing(id)) if id == MODEL_ID));
    }

    #[test]
    fn the_catalog_installs_every_file_the_engine_reads() {
        let catalog = crate::models::Catalog::bundled().unwrap();
        let entry = catalog.find(MODEL_ID).unwrap();
        let names: Vec<&str> = entry.files.iter().map(|f| f.name.as_str()).collect();
        for needed in [
            ENCODER_FILE,
            EMBED_FILE,
            LANGUAGE_MODEL_FILE,
            DECODER_FILE,
            TOKENIZER_FILE,
        ] {
            assert!(names.contains(&needed), "{needed}");
            // ONNX keeps the weights in a sibling file that has to sit next to it.
            if needed != TOKENIZER_FILE {
                assert!(
                    names.contains(&format!("{needed}_data").as_str()),
                    "{needed}_data"
                );
            }
        }
        assert_eq!(entry.kind, crate::models::ModelKind::Clone);
        assert_eq!(entry.license, "MIT");
    }
}
