// Writes THIRD_PARTY_NOTICES.md: every Rust crate the app ships, with its licence, and every model
// in the catalog. Run with `make notices`. Uses only `cargo metadata` and the catalog.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

const OUT = "THIRD_PARTY_NOTICES.md";
const metadata = JSON.parse(
  execFileSync("cargo", ["metadata", "--format-version", "1", "--locked"], {
    maxBuffer: 1 << 28,
  }),
);
const members = new Set(metadata.workspace_members);
const crates = metadata.packages
  .filter((p) => !members.has(p.id))
  .map((p) => ({
    name: p.name,
    version: p.version,
    license: p.license ?? "see the crate",
    repository: p.repository ?? "",
  }))
  .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

const catalog = JSON.parse(readFileSync("catalog/models.json", "utf8"));
const models = catalog.models.map((m) => `| ${m.name ?? m.id} | ${m.license} |`);

const lines = [
  "# Third-party notices",
  "",
  "Voice Studio is built from the software and models below. This file is generated by",
  "`make notices`; do not edit it by hand.",
  "",
  "## Models (downloaded by the user, not bundled)",
  "",
  "| Model | Licence |",
  "| --- | --- |",
  ...models,
  "",
  `## Rust crates (${crates.length})`,
  "",
  "| Crate | Version | Licence |",
  "| --- | --- | --- |",
  ...crates.map((c) => `| ${c.name} | ${c.version} | ${c.license} |`),
  "",
];
writeFileSync(OUT, lines.join("\n"));
process.stdout.write(`wrote ${OUT}: ${crates.length} crates, ${models.length} models\n`);
